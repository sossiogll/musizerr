/**
 * A message that depends on a number: `t(key, { count })` picks the form
 * the locale's plural rules (`Intl.PluralRules`) give for `count`, `other`
 * when the locale has no form of its own for that category.
 */
export interface Plural {
  one: string;
  other: string;
  many?: string;
}

/** Percorsi-foglia (dot path) delle chiavi, derivati dall'inglese. */
type Leaves<T> = T extends string
  ? never
  : {
      [K in keyof T & string]: T[K] extends string | Plural
        ? K
        : `${K}.${Leaves<T[K]>}`;
    }[keyof T & string];

export type MessageKey = Leaves<typeof en>;
export type Locale = "en" | "it";

/**
 * Stessa forma di `T` (chiavi identiche, annidamento identico), ma con le
 * foglie stringa allargate a `string` invece che al loro literal type.
 * `en` è dichiarato `as const` apposta perché `Leaves<T>` possa derivare
 * `MessageKey` dai suoi literal; una traduzione, però, deve poter avere un
 * *valore* diverso per la stessa chiave — vincolarla a `typeof en` la
 * costringerebbe a ripetere pedissequamente l'inglese.
 */
type Translations<T> = {
  [K in keyof T]: T[K] extends string ? string : T[K] extends Plural ? Plural : Translations<T[K]>;
};

